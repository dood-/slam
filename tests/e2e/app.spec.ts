import { test, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
const fixture=fileURLToPath(new URL('./.runtime/fixture.mp4',import.meta.url))
test('upload, reconstruct, seek paused, gaps, models, 3D and persistence',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('/')
 await page.getByLabel('Выбрать MP4',{exact:true}).setInputFiles(fixture)
 await expect(page.locator('video')).toBeVisible()
 await page.getByRole('button',{name:'Восстановить маршрут',exact:true}).click()
 await expect(page.getByLabel('Модель реконструкции')).toBeVisible()
 await expect(page.getByTestId('pose-marker')).toHaveCount(1)
 await page.getByLabel('Время видео',{exact:true}).fill('.6')
 await expect(page.getByTestId('pose-status')).toContainText('Интерполированная')
 await expect.poll(()=>page.locator('video').evaluate((v:HTMLVideoElement)=>v.currentTime)).toBeCloseTo(.6,1)
 await page.getByLabel('Время видео',{exact:true}).fill('1.25')
 await expect(page.getByTestId('pose-status')).toContainText('недоступна')
 await expect(page.getByTestId('pose-marker')).toHaveCount(0)
 await page.getByLabel('Выбрать позу').selectOption('2')
 await expect.poll(()=>page.locator('video').evaluate((v:HTMLVideoElement)=>v.currentTime)).toBeCloseTo(2,1)
 await page.getByRole('button',{name:'3D',exact:true}).click();await expect(page.locator('canvas')).toHaveCount(1)
 await page.getByRole('button',{name:'2D',exact:true}).click();await expect(page.locator('canvas')).toHaveCount(0)
 await page.getByRole('button',{name:'3D',exact:true}).click();await expect(page.locator('canvas')).toHaveCount(1)
 await page.getByRole('button',{name:'2D',exact:true}).click()
 await page.getByLabel('Модель реконструкции').selectOption('alternative')
 await page.getByLabel('Время видео',{exact:true}).fill('.4')
 await expect(page.getByTestId('pose-marker')).toHaveCount(0)
 const downloadPromise=page.waitForEvent('download');await page.getByRole('link',{name:'JSON ↓'}).click();expect((await downloadPromise).suggestedFilename()).toMatch(/\.json$/)
 const csv=await page.request.get((await page.getByRole('link',{name:'CSV ↓'}).getAttribute('href'))!)
 expect(await csv.text()).toContain('modelId,segmentId')
 await page.reload();await page.getByRole('button',{name:/fixture.mp4/}).click()
 await expect(page.getByLabel('Модель реконструкции')).toBeVisible()
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
